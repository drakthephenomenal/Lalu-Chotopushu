#!/usr/bin/env python3
"""build-hcj-langs.py - makes hcj-langs.js (Hit Chaurasi Ji in English, Gujarati, Odia, Punjabi, Telugu)
from the source YAML files.  Usage (repo root):
    python3 build-hcj-langs.py "All source text/chaturasi"
Default folder = ./All source text/chaturasi  (unzip 'All source text.zip' first)."""
import sys, os, re, json
try:
    import yaml
except ImportError:
    sys.exit("needs PyYAML:  pip install pyyaml")

SRC = sys.argv[1] if len(sys.argv) > 1 else "All source text/chaturasi"
LANGS = {  # code: (file, digit set)
    "en": ("verses_english.yaml", "0123456789"),
    "gu": ("verses_gujarati.yaml", "૦૧૨૩૪૫૬૭૮૯"),
    "or": ("verses_oriya.yaml", "୦୧୨୩୪୫୬୭୮୯"),
    "pa": ("verses_punjabi.yaml", "੦੧੨੩੪੫੬੭੮੯"),
    "te": ("verses_telugu.yaml", "౦౧౨౩౪౫౬౭౮౯"),
}

def clean_line(l):
    l = re.sub(r"[ \t]+", " ", l.strip())
    l = re.sub(r"\(\s+", "(", l); l = re.sub(r"\s+\)", ")", l)
    l = re.sub(r"\s+,", ",", l)
    return l

def build(code):
    fn, digits = LANGS[code]
    data = yaml.safe_load(open(os.path.join(SRC, fn), encoding="utf-8"))
    if len(data) != 84:
        sys.exit("%s: expected 84 pads, found %d" % (fn, len(data)))
    blocks = []
    for i, e in enumerate(data):
        n = i + 1
        if int(e["verseNumber"]) != n:
            sys.exit("%s: pad %d has verseNumber %r" % (fn, n, e["verseNumber"]))
        lines = [clean_line(x) for x in str(e["verseText"]).split("\n")]
        lines = [x for x in lines if x]
        colophon = []
        if n == 84 and len(lines) > 2:          # last pad: 2 closing lines come after the verse
            colophon = lines[-2:]; lines = lines[:-2]
        last = re.sub(r"[\s॥।|.]+$", "", lines[-1])
        num = "".join(digits[int(d)] for d in str(n))
        lines[-1] = last + " ॥" + num + "॥"
        blocks.append("\n".join(lines + colophon))
    return "\n\n".join(blocks)

out = {c: build(c) for c in LANGS}
js = "/* Hit Chaurasi Ji - verses in other scripts (no translation). Generated by build-hcj-langs.py */\n"
js += "window.HCJ_EXTRA = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n"
open("hcj-langs.js", "w", encoding="utf-8").write(js)
print("hcj-langs.js written: " + ", ".join("%s=%d KB" % (c, len(v.encode()) // 1024) for c, v in out.items()))
