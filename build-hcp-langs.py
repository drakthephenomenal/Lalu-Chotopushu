#!/usr/bin/env python3
"""build-hcp-langs.py - makes hcp-langs.js (Hit Chaurasi Ji Phalastuti in English, Gujarati, Odia, Punjabi, Telugu)
from the source YAML files.  Usage (repo root):
    python3 build-hcp-langs.py "All source text/chaturasi"
Default folder = ./All source text/chaturasi  (unzip 'All source text.zip' first)."""
import sys, os, re, json
try:
    import yaml
except ImportError:
    sys.exit("needs PyYAML:  pip install pyyaml")

SRC = sys.argv[1] if len(sys.argv) > 1 else "All source text/chaturasi"
LANGS = {"en": "english", "gu": "gujarati", "or": "oriya", "pa": "punjabi", "te": "telugu"}
SHAPE = [1, 12, 1, 8, 9]   # title | phalastuti (2 x 6 lines) | "raag sankhya" heading | raag verse | closing jai lines

def build(code, name):
    d = yaml.safe_load(open(os.path.join(SRC, "extra_pages_after_%s.yaml" % name), encoding="utf-8"))
    lines = []
    for l in str(d[0]["verseText"]).split("\n"):
        l = re.sub(r"[ \t]+", " ", l.strip().replace("\u0315", ""))
        l = re.sub(r"\s+([,])", r"\1", l)
        if l: lines.append(l)
    if len(lines) != sum(SHAPE):
        sys.exit("%s: expected %d lines, found %d" % (name, sum(SHAPE), len(lines)))
    lines[0] = lines[0].replace(" - ", " – ")
    blocks, k = [], 0
    for n in SHAPE:
        blocks.append("\n".join(lines[k:k + n])); k += n
    return "\n\n".join(blocks)

out = {c: build(c, n) for c, n in LANGS.items()}
js = "/* Hit Chaurasi Ji Phalastuti - other scripts. Generated by build-hcp-langs.py */\n"
js += "window.HCP_EXTRA = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n"
open("hcp-langs.js", "w", encoding="utf-8").write(js)
print("hcp-langs.js written: " + ", ".join("%s=%d chars" % (c, len(v)) for c, v in out.items()))
