#!/usr/bin/env python3
"""build-rsn-langs.py - makes rsn-langs.js (Radha Sudha Nidhi shlokas in English, Gujarati, Odia, Punjabi; no meanings)
from the source YAML files.  Usage (repo root):
    python3 build-rsn-langs.py "All source text/radhasudhanidhi"
Default folder = ./All source text/radhasudhanidhi  (unzip 'All source text.zip' first)."""
import sys, os, re, json
try:
    import yaml
except ImportError:
    sys.exit("needs PyYAML:  pip install pyyaml")

SRC = sys.argv[1] if len(sys.argv) > 1 else "All source text/radhasudhanidhi"
# code: (shloka file, vandana file or None when the shloka file already starts with it, header word)
LANGS = {
    "en": ("radhasudhanidhi_english.yaml", "radhasudhanidhi_before_english.yaml", "Shloka"),
    "gu": ("radhasudhanidhi_gujarati.yaml", "radhasudhanidhi_before_gujarati.yaml", "શ્લોક"),
    "or": ("radhasudhanidhi_oriya.yaml", None, "ଶ୍ଲୋକ"),
    "pa": ("radhasudhanidhi_punjabi.yaml", None, "ਸ਼ਲੋਕ"),
}

def load(f):
    return yaml.safe_load(open(os.path.join(SRC, f), encoding="utf-8"))

def lines_of(text):
    out = []
    for l in str(text).split("\n"):
        l = re.sub(r"[ \t]+", " ", l.strip().replace('\u0315', '')).strip('"')
        if l: out.append(l)
    return out

def build(code):
    f, before, word = LANGS[code]
    d = load(f)
    if before:
        vandana = lines_of(load(before)[0]["verseText"])
    else:                                   # first entry is the vandana page
        vandana = lines_of(d[0]["verseText"]); d = d[1:]
    if len(d) != 270:
        sys.exit("%s: expected 270 shlokas, found %d" % (f, len(d)))
    blocks = ["\n".join(vandana)]
    for i, e in enumerate(d):
        n = i + 1
        if int(str(e["verseNumber"]).strip(". ")) != n:
            sys.exit("%s: shloka %d has verseNumber %r" % (f, n, e["verseNumber"]))
        ls = lines_of(e["verseText"])
        tail = []
        if n == 270 and len(ls) > 2:        # closing prayers follow the last shloka (same as the Bengali text)
            tail = ls[2:]; ls = ls[:2]
        ls[-1] = re.sub(r"[\s॥।|]+$", "", ls[-1]) + "॥%d॥" % n
        blocks.append("\n".join(["%s %d:" % (word, n)] + ls + tail))
    return "\n\n".join(blocks)

out = {c: build(c) for c in LANGS}
js = "/* Radha Sudha Nidhi - shlokas in other scripts (no meaning). Generated by build-rsn-langs.py */\n"
js += "window.RSN_EXTRA = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n"
open("rsn-langs.js", "w", encoding="utf-8").write(js)
print("rsn-langs.js written: " + ", ".join("%s=%d KB" % (c, len(v.encode()) // 1024) for c, v in out.items()))
